export function renderArticle(article, chrome) {
  const path = `/articles/${article.slug}`;
  const data = JSON.stringify({
    "@context": "https://schema.org",
    "@type": "BlogPosting",
    headline: article.title,
    description: article.summary,
    datePublished: article.date,
    author: { "@type": "Organization", name: AUTHOR },
    publisher: { "@type": "Organization", name: AUTHOR },
    url: `${SITE}${path}`,
  }, null, 2).replace(/</g, "\\u003c");
  return page({
    title: `${article.title} · WavRead`,
    description: article.summary,
    path,
    ogType: "article",
    bodyClass: "page-article",
    source: article.source,
    head: `<meta property="article:published_time" content="${article.date}">
<script type="application/ld+json">
${data}
</script>
`,
    chrome,
    main: `<div class="page-hero">
<p class="article-crumb"><a href="/articles/index.html">Articles</a></p>
<h1>${escape(article.title)}</h1>
<p class="lede">${escape(article.summary)}</p>
<p class="article-meta"><time datetime="${article.date}">${longDate(article.date)}</time> · By ${AUTHOR}</p>
${lanes(article.lanes)}
</div><div class="reading-layout"><div class="reading-body"><article class="content-section article-body">
${article.html}
</article>
${cta}</div></div>`,
  });
}

export function renderIndex(posts, chrome) {
  const items = posts.map((post) => `<li class="article-item">
<p class="article-meta"><time datetime="${post.date}">${longDate(post.date)}</time></p>
<h2><a href="/articles/${post.slug}.html">${escape(post.title)}</a></h2>
<p>${escape(post.summary)}</p>
${lanes(post.lanes)}
</li>`).join("\n");
  const list = posts.length
    ? `<ol class="article-list">\n${items}\n</ol>`
    : `<p>Nothing is published here yet.</p>`;
  return page({
    title: "Articles · WavRead",
    description: "Notes on what WavRead measures and how its readings get used, for developers, for people working with AI agents, and for musicians.",
    path: "/articles",
    ogType: "website",
    bodyClass: "page-articles",
    source: "content/articles",
    chrome,
    main: `<div class="page-hero">
<h1>Articles</h1>
<p class="lede">Notes on what WavRead measures and how its readings get used. Every post is tagged with the readers it was written for.</p>
${lanes(Object.keys(LANES))}
</div><div class="reading-layout"><div class="reading-body"><section class="content-section" id="articles-list">
${list}
</section>
${cta}</div></div>`,
  });
}

// --------------------------------------------------------------------- sitemap

export function updateSitemap(xml, posts) {
  const start = xml.indexOf(SITEMAP_START);
  const end = xml.indexOf(SITEMAP_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`docs/sitemap.xml: the "${SITEMAP_START} ... -->" and "${SITEMAP_END}" markers are missing, so the articles cannot be listed`);
  }
  const open = xml.indexOf("-->", start) + 3;
  const urls = ["/articles", ...posts.map((post) => `/articles/${post.slug}`)]
    .map((path) => `  <url><loc>${SITE}${path}</loc></url>`).join("\n");
  return `${xml.slice(0, open)}\n${urls}\n  ${xml.slice(end)}`;
}

// ----------------------------------------------------------------------- build

// Everything the build would write, as { "articles/x.html": html, "sitemap.xml": xml },
// relative to docs/. The build writes it; the tests compare it with what is committed.
export async function planArticles({ contentDir, docsDir }) {
  const articles = await loadArticles(contentDir);
  const posts = published(articles);
  const chrome = await readChrome(docsDir);
  const files = new Map();
  files.set("articles/index.html", renderIndex(posts, chrome));
  for (const post of posts) files.set(`articles/${post.slug}.html`, renderArticle(post, chrome));
  files.set("sitemap.xml", updateSitemap(await readFile(join(docsDir, "sitemap.xml"), "utf8"), posts));
  return { files, posts, drafts: articles.filter((article) => article.draft) };
}

export async function buildArticles({ contentDir, docsDir }) {
  const plan = await planArticles({ contentDir, docsDir });
  const out = join(docsDir, "articles");
  await mkdir(out, { recursive: true });
  // docs/articles holds generated pages only. A page the build did not write
  // is refused rather than deleted, so nothing hand-made disappears silently.
  for (const name of await readdir(out)) {
    if (extname(name) !== ".html") continue;
    const html = await readFile(join(out, name), "utf8");
    if (!html.includes(GENERATED)) {
      throw new Error(`docs/articles/${name} was not written by the build; articles come from content/articles, so move or delete it`);
    }
    await rm(join(out, name));
  }
  for (const [path, content] of plan.files) await writeFile(join(docsDir, path), content);
  return plan;
}
