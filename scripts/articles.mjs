// Articles wear the same header and footer as the rest of the site. They are
// read from faq.html at build time rather than copied into this file, so the
// next change to the site's navigation reaches the articles on the next build.
export async function readChrome(docsDir) {
  const faq = await readFile(join(docsDir, "faq.html"), "utf8");
  const header = faq.match(/<header class="header">[\s\S]*?<\/header>/)?.[0];
  const footer = faq.match(/<footer class="wrap product-footer">[\s\S]*?<\/footer>/)?.[0];
  if (!header || !footer) throw new Error("docs/faq.html: could not find the shared header and footer to reuse for articles");
  for (const part of [header, footer]) {
    const relative = [...part.matchAll(/(?:href|src)="([^"]+)"/g)].map((m) => m[1])
      .find((url) => !/^(\/|#|https?:|mailto:)/.test(url));
    if (relative) throw new Error(`docs/faq.html: the shared chrome links "${relative}", which would break under /articles/; make it root-relative`);
  }
  return { header, footer };
}

