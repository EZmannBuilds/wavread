// Articles: Markdown in content/articles becomes static pages in docs/articles.
//
// There are no dependencies on purpose. The frontmatter and the Markdown this
// understands are small, written-down subsets (content/articles/ARTICLES.md),
// and anything outside them stops the build with the file and the reason,
// rather than publishing a page that renders wrongly.

import { readdir, readFile, rm, mkdir, writeFile } from "node:fs/promises";
import { basename, extname, join } from "node:path";

export const LANES = { developer: "Developer", ai: "AI", musician: "Musician" };
export const AUTHOR = "EZmannBuilds";
export const GENERATED = "Generated by scripts/build.mjs";

const SITE = "https://wavread.com";
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const DATE = /^(\d{4})-(\d{2})-(\d{2})$/;
const FIELDS = new Set(["title", "date", "lanes", "summary", "draft"]);
const NOT_POSTS = new Set(["ARTICLES.md", "README.md"]);
const SITEMAP_START = "<!-- articles:start";
const SITEMAP_END = "<!-- articles:end -->";
const MONTHS = ["January", "February", "March", "April", "May", "June", "July",
  "August", "September", "October", "November", "December"];

const escape = (text) => String(text)
  .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
  .replace(/"/g, "&quot;").replace(/'/g, "&#39;");

export const longDate = (iso) => {
  const [, year, month, day] = iso.match(DATE);
  return `${MONTHS[Number(month) - 1]} ${Number(day)}, ${year}`;
};

// ---------------------------------------------------------------- frontmatter

const scalar = (raw) => {
  const quoted = raw.match(/^"(.*)"$/) || raw.match(/^'(.*)'$/);
  if (quoted) return quoted[1];
  if (raw === "true") return true;
  if (raw === "false") return false;
  return raw;
};

const list = (raw) => raw.slice(1, -1).split(",").map((item) => scalar(item.trim())).filter((item) => item !== "");

function parseFrontmatter(lines, fail) {
  const data = {};
  let open = null; // a key whose value is the block list on the following lines
  lines.forEach((line, index) => {
    const at = `line ${index + 2}`;
    if (!line.trim() || line.trim().startsWith("#")) return;
    const item = line.match(/^\s+-\s+(.*)$/);
    if (item) {
      if (!open) return fail(`${at}: a list item without a key above it`);
      data[open].push(scalar(item[1].trim()));
      return;
    }
    const pair = line.match(/^([A-Za-z_][\w-]*):(?:\s+(.*))?$/);
    if (!pair) return fail(`${at}: expected "key: value", got ${JSON.stringify(line)}`);
    const [, key, value = ""] = pair;
    if (!FIELDS.has(key)) return fail(`${at}: unknown field "${key}" (allowed: ${[...FIELDS].join(", ")})`);
    if (key in data) return fail(`${at}: "${key}" is set twice`);
    const raw = value.trim();
    open = null;
    if (raw === "") { data[key] = []; open = key; }
    else if (raw.startsWith("[") && raw.endsWith("]")) data[key] = list(raw);
    else data[key] = scalar(raw);
  });
  return data;
}

function validate(data, fail) {
  for (const key of ["title", "date", "lanes", "summary"]) {
    if (!(key in data)) fail(`missing required field "${key}"`);
  }
  if ("title" in data && (typeof data.title !== "string" || !data.title.trim())) fail(`"title" must be text`);
  if ("date" in data) {
    const match = typeof data.date === "string" && data.date.match(DATE);
    const real = match && (() => {
      const date = new Date(Date.UTC(+match[1], +match[2] - 1, +match[3]));
      return date.getUTCFullYear() === +match[1] && date.getUTCMonth() === +match[2] - 1 && date.getUTCDate() === +match[3];
    })();
    if (!real) fail(`"date" must be an absolute date written YYYY-MM-DD, got ${JSON.stringify(data.date)}`);
  }
  if ("lanes" in data) {
    if (!Array.isArray(data.lanes) || data.lanes.length === 0) {
      fail(`"lanes" must be a list of one or more of: ${Object.keys(LANES).join(", ")}`);
    } else {
      for (const lane of data.lanes) {
        if (!(lane in LANES)) fail(`unknown lane ${JSON.stringify(lane)} (allowed: ${Object.keys(LANES).join(", ")})`);
      }
      if (new Set(data.lanes).size !== data.lanes.length) fail(`"lanes" lists a lane twice`);
    }
  }
  if ("summary" in data) {
    const summary = data.summary;
    if (typeof summary !== "string" || !summary.trim()) fail(`"summary" must be text`);
    else if (!/[.!?]$/.test(summary) || /[.!?]\s+\S/.test(summary)) {
      fail(`"summary" must be exactly one sentence, ending in . ! or ?`);
    }
  }
  if ("draft" in data && typeof data.draft !== "boolean") {
    fail(`"draft" must be true or false, got ${JSON.stringify(data.draft)}`);
  }
}

// ------------------------------------------------------------------- markdown

function inline(text, fail) {
  const held = [];
  const hold = (html) => `\u0000${held.push(html) - 1}\u0000`;
  let out = text.replace(/`([^`]+)`/g, (_, code) => hold(`<code>${escape(code)}</code>`));
  if (/!\[/.test(out)) fail(`images are not supported yet: ${JSON.stringify(text)}`);
  out = escape(out);
  out = out.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, label, url) => {
    if (!/^(https:\/\/|http:\/\/|mailto:|\/|#)/.test(url)) {
      fail(`link ${JSON.stringify(url)} must start with https://, mailto:, / or #`);
    }
    return hold(`<a href="${url}">${emphasis(label)}</a>`);
  });
  out = emphasis(out);
  // A held link can itself hold code, so restore until nothing is left held.
  while (/\u0000\d+\u0000/.test(out)) out = out.replace(/\u0000(\d+)\u0000/g, (_, index) => held[Number(index)]);
  return out;
}

const emphasis = (html) => html
  .replace(/\*\*(?=\S)(.+?)\*\*/g, "<strong>$1</strong>")
  .replace(/\*(?=\S)(.+?)\*/g, "<em>$1</em>");

const anchor = (text, used) => {
  const base = text.toLowerCase().replace(/<[^>]+>/g, "").replace(/&[a-z#0-9]+;/g, "")
    .replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "section";
  let id = base;
  for (let n = 2; used.has(id); n++) id = `${base}-${n}`;
  used.add(id);
  return id;
};

export function renderMarkdown(source, fail = (message) => { throw new Error(message); }, used = new Set()) {
  const lines = source.replace(/\r\n?/g, "\n").split("\n");
  const html = [];
  let paragraph = [];
  const flush = () => {
    if (paragraph.length) html.push(`<p>${inline(paragraph.join(" "), fail)}</p>`);
    paragraph = [];
  };
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!line.trim()) { flush(); continue; }
    const fence = line.match(/^```/);
    if (fence) {
      flush();
      const start = i;
      const code = [];
      while (++i < lines.length && !/^```\s*$/.test(lines[i])) code.push(lines[i]);
      if (i >= lines.length) { fail(`the code block opened on body line ${start + 1} is never closed`); break; }
      html.push(`<pre><code>${escape(code.join("\n"))}</code></pre>`);
      continue;
    }
    const heading = line.match(/^(#{1,6})\s+(.+?)\s*$/);
    if (heading) {
      flush();
      const level = heading[1].length;
      if (level === 1) { fail(`"# ${heading[2]}": the title is the page's only h1, so sections start at ##`); continue; }
      if (level > 4) { fail(`"${line}": headings go no deeper than ####`); continue; }
      const content = inline(heading[2], fail);
      html.push(level === 2
        ? `<h2 id="${anchor(content, used)}">${content}</h2>`
        : `<h${level}>${content}</h${level}>`);
      continue;
    }
    if (/^(?:-{3,}|\*{3,})\s*$/.test(line)) { flush(); html.push("<hr>"); continue; }
    if (/^\s*\|/.test(line)) { fail(`tables are not supported yet: ${JSON.stringify(line)}`); continue; }
    if (/^>/.test(line)) {
      flush();
      const quoted = [];
      for (; i < lines.length && /^>/.test(lines[i]); i++) quoted.push(lines[i].replace(/^>\s?/, ""));
      i--;
      html.push(`<blockquote>${renderMarkdown(quoted.join("\n"), fail, used)}</blockquote>`);
      continue;
    }
    const bullet = /^[-*]\s+/;
    const number = /^\d+\.\s+/;
    if (bullet.test(line) || number.test(line)) {
      flush();
      const marker = bullet.test(line) ? bullet : number;
      const items = [];
      for (; i < lines.length; i++) {
        if (marker.test(lines[i])) items.push(lines[i].replace(marker, ""));
        else if (/^\s+\S/.test(lines[i]) && items.length) items[items.length - 1] += ` ${lines[i].trim()}`;
        else break;
      }
      i--;
      const tag = marker === bullet ? "ul" : "ol";
      html.push(`<${tag}>${items.map((item) => `<li>${inline(item, fail)}</li>`).join("")}</${tag}>`);
      continue;
    }
    paragraph.push(line.trim());
  }
  flush();
  return html.join("\n");
}

// ---------------------------------------------------------------------- posts

export function parseArticle(file, text) {
  const errors = [];
  const fail = (message) => errors.push(`${file}: ${message}`);
  const slug = basename(file, ".md");
  if (!SLUG.test(slug) || slug === "index") {
    fail(`the file name is the URL, so it must be lowercase words joined by hyphens (and not "index")`);
  }
  const lines = text.replace(/\r\n?/g, "\n").split("\n");
  const close = lines.indexOf("---", 1);
  if (lines[0] !== "---" || close === -1) {
    fail(`must start with frontmatter between two "---" lines`);
    return { errors };
  }
  const data = parseFrontmatter(lines.slice(1, close), (message) => fail(`frontmatter ${message}`));
  if (errors.length === 0) validate(data, (message) => fail(`frontmatter: ${message}`));
  const body = lines.slice(close + 1).join("\n");
  if (!body.trim()) fail(`has no body below the frontmatter`);
  const html = renderMarkdown(body, (message) => fail(message));
  return {
    errors,
    article: {
      slug, source: file, html,
      title: data.title, date: data.date, lanes: data.lanes, summary: data.summary,
      draft: data.draft ?? false,
    },
  };
}

export async function loadArticles(contentDir) {
  const names = (await readdir(contentDir)).filter((name) => extname(name) === ".md" && !NOT_POSTS.has(name)).sort();
  const errors = [];
  const articles = [];
  for (const name of names) {
    const result = parseArticle(join("content/articles", name), await readFile(join(contentDir, name), "utf8"));
    errors.push(...result.errors);
    if (result.errors.length === 0) articles.push(result.article);
  }
  if (errors.length) {
    throw new Error(`${errors.length} problem${errors.length === 1 ? "" : "s"} in content/articles:\n  ${errors.join("\n  ")}`);
  }
  return articles;
}

// Newest first; posts from the same day in a stable, alphabetical order.
export const published = (articles) => articles.filter((article) => !article.draft)
  .sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));

